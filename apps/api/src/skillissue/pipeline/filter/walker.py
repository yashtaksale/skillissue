"""File walker that applies directory, file, and content filters."""
from __future__ import annotations

import hashlib
import os
from dataclasses import dataclass
from pathlib import Path
from typing import BinaryIO

from skillissue.pipeline.filter.language import detect
from skillissue.pipeline.filter.loc import count_loc
from skillissue.pipeline.filter.types import FileInfo

# =====================================================================
# Excluded directory names (case-insensitive match against leaf name)
# =====================================================================
_EXCLUDED_DIRS: frozenset[str] = frozenset(
    {
        "node_modules", "vendor", "third_party", "dist", "build", "out",
        "target", ".next", ".nuxt", ".svelte-kit", ".venv", "venv",
        "env", "__pycache__", ".git", ".idea", ".vscode", "coverage",
        ".cache", ".gradle", "Pods", "bower_components",
    }
)

# =====================================================================
# File-level exclusion patterns
# =====================================================================
_EXCLUDED_SUFFIXES: tuple[str, ...] = (
    ".min.js", ".min.css", ".map", ".lock",
)

# Binary extensions (image, font, archive, media)
_BINARY_EXTENSIONS: frozenset[str] = frozenset(
    {
        ".png", ".jpg", ".jpeg", ".gif", ".ico", ".svg", ".bmp", ".tiff",
        ".webp", ".psd", ".eps",
        ".woff", ".woff2", ".ttf", ".eot", ".otf",
        ".zip", ".tar", ".gz", ".bz2", ".xz", ".7z", ".rar",
        ".tar.gz", ".tgz", ".tar.bz2", ".tar.xz",
        ".mp3", ".mp4", ".wav", ".flac", ".aac", ".ogg", ".avi",
        ".mov", ".mkv", ".wmv", ".m4a", ".opus",
        ".pdf", ".doc", ".docx", ".xls", ".xlsx", ".ppt", ".pptx",
        ".exe", ".dll", ".so", ".dylib", ".bin", ".o", ".a", ".lib",
        ".pyc", ".pyo", ".class", ".jar", ".war", ".ear",
        ".wasm", ".db", ".sqlite", ".sqlite3", ".mdb",
        ".iso", ".dmg", ".img", ".vmdk", ".qcow2",
        ".dat", ".pak",
    }
)

_MAX_FILE_BYTES = 1 * 1024 * 1024       # 1 MB
_MAX_FILE_LINES = 5_000
_BINARY_SCAN_BYTES = 8 * 1024           # first 8 KB for NUL detection
_GENERATED_HEAD_LINES = 20

_GENERATED_MARKERS: tuple[str, ...] = (
    "auto-generated",
    "autogenerated",
    "generated by",
    "do not edit",
    "@generated",
)

# Lockfile extensions (collected as manifests, not source files)
_LOCKFILE_SUFFIXES: tuple[str, ...] = (
    ".lock",
    ".lockb",
)


# =====================================================================
# Helpers
# =====================================================================


def _has_nul_byte(path: Path) -> bool:
    """Check the first 8 KB of a file for NUL bytes."""
    try:
        with open(path, "rb") as fh:
            chunk = fh.read(_BINARY_SCAN_BYTES)
        return b"\x00" in chunk
    except OSError:
        return False


def _looks_like_lockfile(path: Path) -> bool:
    """True if the file is a lockfile (matched by extension or common names)."""
    name = path.name.lower()
    if any(name.endswith(s) for s in _LOCKFILE_SUFFIXES):
        return True
    # Common lockfile basenames
    lock_basenames = {
        "package-lock.json", "yarn.lock", "pnpm-lock.yaml",
        "bun.lock", "bun.lockb", "poetry.lock", "Pipfile.lock",
        "uv.lock", "pdm.lock", "cargo.lock", "go.sum",
        "gemfile.lock", "composer.lock", "mix.lock",
    }
    if name in lock_basenames:
        return True
    return False


def _is_generated(path: Path) -> bool:
    """Check the first 20 lines for auto-generated markers (case-insensitive)."""
    try:
        with open(path, "rb") as fh:
            raw = b""
            for _ in range(_GENERATED_HEAD_LINES):
                line = fh.readline()
                if not line:
                    break
                raw += line
        head = raw.decode("utf-8", errors="replace").lower()
        return any(marker in head for marker in _GENERATED_MARKERS)
    except OSError:
        return False


def _excluded_dir(name: str) -> bool:
    return name.casefold() in _EXCLUDED_DIRS


def _excluded_file(path: Path) -> bool:
    name = path.name
    lower = name.lower()
    # Suffix-based exclusions
    if any(lower.endswith(s) for s in _EXCLUDED_SUFFIXES):
        return True
    # Binary extension check
    ext_start = lower.rfind(".")
    if ext_start != -1:
        ext = lower[ext_start:]
        if ext in _BINARY_EXTENSIONS:
            return True
        # Handle multi-part extensions like .tar.gz
        if ext_start > 0:
            parent_ext = lower[ext_start - 1 :]  # e.g. ".tar.gz" starting at '-1' won't work
        # Check multi-part
        parts = lower.split(".")
        if len(parts) >= 2:
            for i in range(len(parts) - 1):
                multi = "." + ".".join(parts[i:])
                if multi in _BINARY_EXTENSIONS:
                    return True
    return False


def _sha256_of(path: Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as fh:
        for chunk in iter(lambda: fh.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


# =====================================================================
# Public API
# =====================================================================


@dataclass
class WalkResult:
    """Results of a directory walk."""
    files: list[FileInfo]
    manifests: list[str]  # relative paths of lockfiles


def walk(source_dir: Path | str) -> WalkResult:
    """Walk *source_dir* and return filtered FileInfo objects plus manifests.

    Args:
        source_dir: Root directory of an extracted repository.

    Returns:
        WalkResult with included files and lockfile manifest paths.
    """
    source_dir = Path(source_dir)
    files: list[FileInfo] = []
    manifests: list[str] = []

    for root, dirs, files_in_dir in os.walk(source_dir):
        # Prune excluded directories (in-place modifies what os.walk sees)
        dirs[:] = [d for d in dirs if not _excluded_dir(d)]
        # Skip hidden directories at any depth beyond the excluded list
        dirs[:] = sorted(dirs)  # deterministic ordering

        for fname in files_in_dir:
            full_path = Path(root) / fname

            # Compute relative path from source_dir
            try:
                rel_path = full_path.relative_to(source_dir)
            except ValueError:
                rel_path = full_path

            rel_str = str(rel_path).replace("\\", "/")

            # File-level exclusions
            if _excluded_file(full_path):
                if _looks_like_lockfile(full_path):
                    manifests.append(rel_str)
                continue

            # Size limit
            try:
                stat = full_path.stat()
            except OSError:
                continue
            if stat.st_size > _MAX_FILE_BYTES:
                continue

            # Binary: NUL byte in first 8 KB
            if _has_nul_byte(full_path):
                continue

            # Read head for language detection + generated check
            try:
                with open(full_path, "rb") as fh:
                    head_bytes = fh.read(2048)
            except OSError:
                continue

            # Generated file check
            if _is_generated(full_path):
                continue

            # Language detection
            lang = detect(rel_str, head_bytes)

            # LOC count
            try:
                content = head_bytes.decode("utf-8", errors="replace")
            except Exception:
                continue
            total_lines, loc = count_loc(content, lang)

            # Line limit
            if total_lines > _MAX_FILE_LINES:
                continue

            sha256 = _sha256_of(full_path)

            files.append(FileInfo(
                path=rel_str,
                lang=lang,
                loc=loc,
                bytes=stat.st_size,
                sha1=sha256,
            ))

    return WalkResult(files=files, manifests=manifests)
